"""Generate browser/tls/trusted_roots.h from a Mozilla CA bundle (PEM, e.g. python-certifi's cacert.pem).

    python3 tools/gen_roots.py /path/to/cacert.pem [--keep-order OLD_trusted_roots.h]

Usable roots: RSA up to 4096 bits, ECDSA P-256 / P-384 (what x509.h/pkcs1.h/ecc.h can verify with).
Everything else (P-521, Ed25519, RSA > 4096) is listed in roots/SKIPPED.txt. A root whose label matches
--exclude (default: 'egress', the sandbox's private gateway CAs) is never embedded.
Writes roots/ROOTS.txt (label, SHA-256, key) next to the header for auditing.
"""
import argparse, base64, hashlib, re, subprocess, sys, os

def pem_blocks(text):
    label = None; fp = None
    for m in re.finditer(r'((?:^#[^\n]*\n)*)-----BEGIN CERTIFICATE-----\n(.*?)-----END CERTIFICATE-----', text, re.S | re.M):
        meta = m.group(1)
        lab = re.search(r'^# Label: "(.*)"', meta, re.M)
        sha = re.search(r'^# SHA256 Fingerprint: ([0-9A-Fa-f:]+)', meta, re.M)
        der = base64.b64decode(''.join(m.group(2).split()))
        yield (lab.group(1) if lab else None), (sha.group(1).replace(':', '').lower() if sha else None), der

def keyinfo(der):
    t = subprocess.run(['openssl', 'x509', '-inform', 'DER', '-noout', '-text'], input=der, capture_output=True).stdout.decode('latin1')
    if 'rsaEncryption' in t:
        b = int(re.search(r'Public-Key: \((\d+) bit\)', t).group(1))
        return ('RSA %d-bit' % b, b <= 4096)
    if 'id-ecPublicKey' in t:
        c = re.search(r'ASN1 OID: (\S+)', t).group(1)
        return ('ECDSA %s' % c, c in ('prime256v1', 'secp384r1'))
    return (re.search(r'Public Key Algorithm: (\S+)', t).group(1), False)

def old_hashes(path):
    s = open(path).read(); out = []
    for m in re.finditer(r'static const u8 ROOT_\d+\[\] = \{(.*?)\};', s, re.S):
        out.append(hashlib.sha256(bytes(int(x) for x in re.findall(r'\d+', m.group(1)))).hexdigest())
    return out

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('bundle'); ap.add_argument('--extra', action='append', default=[], help='more PEM files to merge (e.g. roots you decide to keep)'); ap.add_argument('--removed-from', help='previous trusted_roots.h: roots missing from the new bundle are listed in roots/REMOVED.txt'); ap.add_argument('--keep-order'); ap.add_argument('--exclude', default='egress')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'browser', 'tls', 'trusted_roots.h'))
    ap.add_argument('--version', default='')
    a = ap.parse_args()
    roots, skipped = [], []
    seen = set()
    for lab, sha, der in [b for f in [a.bundle] + a.extra for b in pem_blocks(open(f).read())]:
        h = hashlib.sha256(der).hexdigest()
        if h in seen: continue
        seen.add(h)
        if sha and sha != h: sys.exit('fingerprint mismatch for %s' % lab)
        lab = lab or h[:16]
        if a.exclude and a.exclude.lower() in lab.lower(): skipped.append((lab, h, 'excluded by name')); continue
        k, ok = keyinfo(der)
        (roots if ok else skipped).append((lab, h, k, der) if ok else (lab, h, k))
    if a.keep_order:
        order = {h: i for i, h in enumerate(old_hashes(a.keep_order))}
        roots.sort(key=lambda r: (order.get(r[1], 10**6), r[0].lower()))
    else:
        roots.sort(key=lambda r: r[0].lower())
    out = open(a.out, 'w')
    out.write('''/* GENERATED by tools/gen_roots.py -- do not edit by hand. */
#ifndef TRUSTED_ROOTS_H
#define TRUSTED_ROOTS_H
#include "io.h"

/* Embedded trust anchors: the Mozilla root program's TLS server roots (python-certifi bundle%s),
 * restricted to the key types this client can verify (RSA up to 4096 bits, ECDSA P-256/P-384).
 * Skipped roots and the reason are listed in roots/SKIPPED.txt; every embedded root with its SHA-256
 * is listed in roots/ROOTS.txt. The bundle is Mozilla data under the Mozilla Public License 2.0
 * (see NOTICE.md). A root's OWN signature is never checked (it is trusted because it is listed).
 * Roots that Mozilla removed or distrusts disappear on the next regeneration; this client has no
 * "distrust after" date handling, so a root that Mozilla only partially distrusts stays listed.
 * Regenerate: python3 tools/gen_roots.py cacert.pem --keep-order browser/tls/trusted_roots.h */
''' % ((', ' + a.version) if a.version else ''))
    for i, (lab, h, k, der) in enumerate(roots):
        out.write('/* %s (%s) */\n' % (lab.replace('*/', '* /'), k))
        out.write('static const u32 ROOT_%03d_len = %d;\nstatic const u8 ROOT_%03d[] = {\n' % (i, len(der), i))
        for j in range(0, len(der), 16):
            out.write('    ' + ','.join(str(b) for b in der[j:j + 16]) + ',\n')
        out.write('};\n\n')
    n = len(roots)
    out.write('#define TRUSTED_ROOT_COUNT %d\n\nstatic const u8 *const trusted_roots[TRUSTED_ROOT_COUNT] = {\n' % n)
    for i in range(n): out.write('    ROOT_%03d,\n' % i)
    out.write('};\n\nstatic const u32 trusted_root_lens[TRUSTED_ROOT_COUNT] = {\n')
    for i in range(n): out.write('    ROOT_%03d_len,\n' % i)
    out.write('};\n\n#endif\n'); out.close()
    d = os.path.join(os.path.dirname(__file__), '..', 'roots'); os.makedirs(d, exist_ok=True)
    open(os.path.join(d, 'ROOTS.txt'), 'w').write(''.join('%s  %-22s %s\n' % (h, k, lab) for lab, h, k, _ in roots))
    open(os.path.join(d, 'SKIPPED.txt'), 'w').write(''.join('%s  %-22s %s\n' % (h, k, lab) for lab, h, k in skipped))
    if a.removed_from:
        names = {}
        t = open(a.removed_from).read()
        for m in re.finditer(r'/\* ([^\n]*?) \*/\nstatic const u32 ROOT_\d+_len = \d+;\nstatic const u8 ROOT_\d+\[\] = \{(.*?)\};', t, re.S):
            names[hashlib.sha256(bytes(int(x) for x in re.findall(r'\d+', m.group(2)))).hexdigest()] = m.group(1)
        have = {r[1] for r in roots}
        open(os.path.join(d, 'REMOVED.txt'), 'w').write(''.join('%s  %s\n' % (h, nm) for h, nm in names.items() if h not in have))
    print('%d roots written, %d skipped' % (n, len(skipped)))

main()
