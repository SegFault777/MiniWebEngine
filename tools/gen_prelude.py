"""Turn src/mwe_js_prelude.js into src/mwe_js_prelude.h (a C string constant, one literal per line)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'src', 'mwe_js_prelude.js'), encoding='utf-8').read()
out = ['/* GENERATED by tools/gen_prelude.py from mwe_js_prelude.js -- do not edit. */', 'static const char MWE_JS_PRELUDE[] =']
for line in src.split('\n'):
    out.append('"' + line.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
out.append(';')
open(os.path.join(here, '..', 'src', 'mwe_js_prelude.h'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('mwe_js_prelude.h: %d lines' % len(src.split('\n')))
