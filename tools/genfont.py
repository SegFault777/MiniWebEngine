"""Convert a Regular + Bold font (TTF/OTF) into src/mwe_font.h for MiniWebEngine.

    pip install fonttools
    python3 tools/genfont.py Inter-Regular.ttf Inter-Bold.ttf -o mwe_font.h

Outlines are quantized to a 1024-unit em, converted to quadratic curves and
delta/varint encoded. Only ASCII plus a few typographic extras are embedded.
Use static fonts (not the variable font). Inter is licensed under the SIL OFL.
"""
import argparse
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
from fontTools.pens.cu2quPen import Cu2QuPen

EXTRA = [0xA0, 0xA9, 0xAE, 0xB0, 0xB7, 0xD7, 0xAB, 0xBB, 0x2013, 0x2014,
         0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2192, 0x20AC]
UNITS = 1024


class Rec(BasePen):
    def __init__(self, gs, k):
        super().__init__(gs)
        self.k, self.ops = k, []

    def q(self, p):
        return (round(p[0] * self.k), round(p[1] * self.k))

    def _moveTo(self, p): self.ops.append(('m', self.q(p)))
    def _lineTo(self, p): self.ops.append(('l', self.q(p)))
    def _qCurveToOne(self, c, p): self.ops.append(('q', self.q(c), self.q(p)))
    def _curveToOne(self, a, b, c): raise RuntimeError('cubic reached pen')
    def _closePath(self): self.ops.append(('z',))
    def _endPath(self): self.ops.append(('z',))


def vi(out, v):
    z = v * 2 if v >= 0 else -v * 2 - 1
    while z >= 128:
        out.append((z & 127) | 128)
        z >>= 7
    out.append(z)


def enc(ops):
    out = bytearray()
    cx = cy = sx = sy = 0
    for o in ops:
        if o[0] == 'm':
            out.append(1); x, y = o[1]; vi(out, x - cx); vi(out, y - cy)
            cx, cy, sx, sy = x, y, x, y
        elif o[0] == 'l':
            out.append(2); x, y = o[1]; vi(out, x - cx); vi(out, y - cy); cx, cy = x, y
        elif o[0] == 'q':
            out.append(3); (qx, qy), (x, y) = o[1], o[2]
            vi(out, qx - cx); vi(out, qy - cy); vi(out, x - qx); vi(out, y - qy)
            cx, cy = x, y
        else:
            out.append(4); cx, cy = sx, sy
    out.append(0)
    return bytes(out)


def load(path, cps):
    f = TTFont(path)
    k = UNITS / f['head'].unitsPerEm
    cmap, gs, hm = f.getBestCmap(), f.getGlyphSet(), f['hmtx']
    data, adv = [], []
    for cp in cps:
        g = cmap[cp]
        rec = Rec(gs, k)
        gs[g].draw(Cu2QuPen(rec, max_err=1.0 / k * 0.5, reverse_direction=False))
        data.append(enc(rec.ops))
        adv.append(round(hm[g][0] * k))
    hh = f['hhea']
    return dict(f=f, data=data, adv=adv, asc=round(hh.ascent * k),
                desc=round(-hh.descent * k), fam=f['name'].getDebugName(1),
                cmap=set(cmap))


def arr(vals, w=20):
    return ',\n'.join(','.join(str(v) for v in vals[i:i + w]) for i in range(0, len(vals), w))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('regular'); ap.add_argument('bold')
    ap.add_argument('-o', '--out', default='mwe_font.h')
    ap.add_argument('--name', help='font label embedded in the header')
    a = ap.parse_args()
    probe = [TTFont(a.regular).getBestCmap(), TTFont(a.bold).getBestCmap()]
    cps = list(range(32, 127))
    for cp in EXTRA:
        if all(cp in c for c in probe): cps.append(cp)
        else: print('warning: U+%04X missing, skipped' % cp)
    r, b = load(a.regular, cps), load(a.bold, cps)
    label = a.name or '%s Regular+Bold' % r['fam']
    offs = []
    for w in (r, b):
        o, t = [], 0
        for d in w['data']: o.append(t); t += len(d)
        o.append(t); assert t < 65536; offs.append(o)
    with open(a.out, 'w') as o:
        o.write('/* GENERATED by tools/genfont.py -- do not edit. Source: %s */\n' % label)
        o.write('/* Font outlines are licensed under the SIL Open Font License 1.1 (see fonts/). */\n')
        o.write('#define MF_NAME "%s"\n#define MF_UPM %d\n#define MF_ASC %d\n#define MF_DESC %d\n#define MF_N %d\n'
                % (label, UNITS, r['asc'], r['desc'], len(cps)))
        o.write('static const unsigned short MF_CP[MF_N]={%s};\n' % ','.join(map(str, cps)))
        o.write('static const unsigned short MF_ADV[2][MF_N]={{%s},{%s}};\n' % (arr(r['adv']), arr(b['adv'])))
        o.write('static const unsigned short MF_OFF[2][MF_N+1]={{%s},{%s}};\n' % (arr(offs[0]), arr(offs[1])))
        for n, w in enumerate((r, b)):
            o.write('static const unsigned char MF_D%d[]={\n%s};\n' % (n, arr(list(b''.join(w['data'])), 24)))
    print('%s: %d glyphs, data %d + %d bytes, asc %d desc %d' % (a.out, len(cps), offs[0][-1], offs[1][-1], r['asc'], r['desc']))


if __name__ == '__main__':
    main()
